/// 날짜 번호 (하루에 1씩 는다). 같은 날에는 같은 문장이 나오고, 다음 날에는 다음 문장으로 넘어간다.
int dayNumber(DateTime d) => DateTime.utc(d.year, d.month, d.day).millisecondsSinceEpoch ~/ Duration.millisecondsPerDay;

/// [day]번째 날의 문장.
T cheerOf<T>(List<T> lines, int day) => lines[day % lines.length];

